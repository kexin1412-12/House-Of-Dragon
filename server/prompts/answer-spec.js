function buildAnswerSpec(depth) {
  const normalized = depth === 'oneline' || depth === 'deep' ? depth : 'brief';

  if (normalized === 'oneline') {
    return `

<output_contract mode="oneline">
- 只输出一句，最多 28 个中文字符。
- 不使用 [事实]、[解读]、[推测] 标签。
- 直接给结论，不用“是的”“这是”“画面中”开头。
</output_contract>`;
  }

  if (normalized === 'deep') {
    return `

<output_contract mode="deep">
总长度控制在 380-560 个中文字符。按以下层次输出，每个标签最多出现一次：

[事实] 60-100 字
- 先回答具体人物、物件和事件，再给一至两个最有辨识度的可见证据。
- timed_visual_beat 已核验的信息优先，不得被单帧猜测覆盖。

[解读] 280-420 字
- 最多三段：核心寓意；必要的历史或人物关联；对当前剧情的镜像或艺术作用。
- 开头先给鲜明的核心论断。至少建立一组具体反差，并用一个当前画面的意象贯穿。
- 每段只承担一个作用，不复述 [事实]，不换近义词重复同一判断。
- 删除任何可以套用到其他镜头的泛泛句子；资料不足时宁可提前结束，不为凑长度注水。
- 结尾可用一句克制、有余味的主题收束，但不得再总结全文。

[推测] 40-70 字
- 只写真实存在的争议或证据边界。
- 区分已核验事实、剧集视觉化、常见解读；不为满足格式编造可能性。
- 没有实质争议时完全省略本层。
</output_contract>`;
  }

  return `

<output_contract mode="brief">
- 默认输出 [事实] 与 [解读] 两层，每个标签只出现一次。
- 总长度控制在 160-240 个中文字符，写成两段紧凑短文。
- [事实] 45-75 字：明确回答“谁、在做什么、这是哪一事件”，并给一个可见证据；无必要可省略。
- [解读] 100-165 字：先给核心寓意，再补一条最关键的历史或当前剧情联系。
- 不复述画面，不罗列背景，不写可套用于任何场景的“象征权力、勇气、复杂关系”。
- 每句话必须增加新信息；证据不足时宁可短于下限，不得用空话凑字数。
- 用户没有询问可能性时，不输出 [推测]。
</output_contract>`;
}

module.exports = { buildAnswerSpec };
